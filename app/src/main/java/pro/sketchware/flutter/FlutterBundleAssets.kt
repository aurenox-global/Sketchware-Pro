    /**
     * `FontManifest.json` como el del SDK: `[{"family":..,"fonts":[{"asset":..[,"weight"][,"style"]]}]}]`.
     *
     * La familia `MaterialIcons` **solo** se emite si la fuente esta en el bundle (si no, dejar la
     * entrada haria que el motor intente cargar un asset inexistente).
     */
    @JvmStatic
    fun buildFontManifestJson(projectRoot: File, includeMaterialIcons: Boolean): String {
        val families = ArrayList<List<Any>>()
        if (includeMaterialIcons) {
            val font = LinkedHashMap<String, Any>()
            font["asset"] = MATERIAL_ICONS_ENTRY
            families.add(listOf(mapOf("family" to MATERIAL_ICONS_FAMILY, "fonts" to listOf(font))))
        }
        for (family in parsePubspecFonts(File(projectRoot, "pubspec.yaml"))) {
            val fonts = ArrayList<Map<String, Any>>()
            for (entry in family.fonts) {
                val font = LinkedHashMap<String, Any>()
                font["asset"] = entry.asset
                entry.weight?.let { font["weight"] = it }
                entry.style?.let { font["style"] = it }
                fonts.add(font)
            }
            if (fonts.isEmpty()) continue
            val item = LinkedHashMap<String, Any>()
            item["family"] = family.family
            item["fonts"] = fonts
            families.add(listOf(item))
        }
        return families.joinToString(separator = ",", prefix = "[", postfix = "]") { list ->
            list.joinToString(separator = ",") { entry -> encodeJsonValue(entry) }
        }
    }

    // ---------------------------------------------------------------------------------------------
    // AssetManifest (binario + json)
    // ---------------------------------------------------------------------------------------------

    /**
     * `AssetManifest.bin`: `StandardMessageCodec().encodeMessage` de
     * `Map<String, List<Map<String, Object>>>` con `"asset"` (String) y, si la ruta lleva carpeta
     * de densidad (`2.0x`), `"dpr"` (Float64). Identico a `_createAssetManifestBinary` de
     * flutter_tools (`asset.dart`).
     *
     * OJO: `dpr` va como **Float64** (tag 6), no como entero: el framework hace
     * `dpr as double?` y un Int32 (tag 3) lanzaria `TypeError`.
     */
    @JvmStatic
    fun buildAssetManifestBinary(entries: Map<String, List<String>>): ByteArray {
        val root = LinkedHashMap<String, Any>()
        for (key in entries.keys.sorted()) {
            val variants = ArrayList<Any>()
            for (variant in entries[key].orEmpty()) {
                val item = LinkedHashMap<String, Any>()
                item["asset"] = variant
                densityOf(variant)?.let { item["dpr"] = it }
                variants.add(item)
            }
            root[key] = variants
        }
        val out = ByteArrayOutputStream(4096)
        writeStandardValue(out, root)
        return out.toByteArray()
    }

    /** Espejo legible (`AssetManifest.json`, el formato que usaba Flutter < 3.19). */
    @JvmStatic
    fun buildAssetManifestJson(entries: Map<String, List<String>>): String {
        val root = LinkedHashMap<String, Any>()
        for (key in entries.keys.sorted()) {
            root[key] = entries[key].orEmpty().toList()
        }
        return encodeJsonValue(root)
    }

    /** Densidad (`dpr`) deducida del nombre de la carpeta padre, como `_extractPixelRatioFromKeyRegExp`. */
    @JvmStatic
    fun densityOf(assetPath: String): Double? {
        val parts = assetPath.split('/').filter { it.isNotEmpty() }
        if (parts.size < 2) return null
        val match = DENSITY_DIR_REGEX.find(parts[parts.size - 2]) ?: return null
        return match.groupValues[1].toDoubleOrNull()
    }

