    /**
     * Fuentes de assets que [buildFlutterAssets] copia al bundle.
     *
     * @param materialIconsFont `MaterialIcons-Regular.otf` (o `null` si no se pudo obtener: el
     *   bundle se generara igual, con aviso y sin entrada Material en `FontManifest.json`).
     * @param shaders ficheros `.frag` ya precompilados que se copian a `flutter_assets/shaders/`.
     * @param licenseFiles ficheros de licencia en texto plano para `NOTICES.Z`.
     */
    class Sources @JvmOverloads constructor(
        @JvmField val materialIconsFont: File? = null,
        @JvmField val shaders: List<File> = emptyList(),
        @JvmField val licenseFiles: List<File> = emptyList(),
    )

    /** Resultado del poblado (lo que hay que registrar/telemetrear desde el compilador). */
    class BundleAssetsResult(
        @JvmField val success: Boolean,
        @JvmField val fontIncluded: Boolean,
        @JvmField val shaderCount: Int,
        @JvmField val assetEntryCount: Int,
        @JvmField val hiddenVariantCount: Int,
        @JvmField val noticesBytes: Long,
        @JvmField val log: String,
    ) {
        override fun toString(): String =
            "BundleAssetsResult(success=$success, font=$fontIncluded, shaders=$shaderCount, " +
                "assets=$assetEntryCount, variantes=$hiddenVariantCount, NOTICES.Z=$noticesBytes B)"
    }

    /**
     * Version "de toolchain": coge las fuentes de la cache del engine y escribe en
     * `<flutterRoot>/build/flutter_assets`.
     */
    @JvmStatic
    fun populateFlutterAssets(
        context: Context,
        flutterRoot: File,
        progress: (String) -> Unit,
    ): BundleAssetsResult = populateFlutterAssets(
        context,
        FlutterToolchainPaths.flutterAssetsDir(flutterRoot),
        flutterRoot,
        progress,
    )

    /**
     * Version explicita (la que se llama desde `FlutterDartCompiler`): escribe en
     * [flutterAssetsDir] y resuelve los assets declarados en el pubspec de [projectRoot].
     */
    @JvmStatic
    fun populateFlutterAssets(
        context: Context,
        flutterAssetsDir: File,
        projectRoot: File,
        progress: (String) -> Unit,
    ): BundleAssetsResult {
        val sources = Sources(
            materialIconsFont = materialIconsFontFile(context).takeIf { it.isFile },
            shaders = listOf(inkSparkleShaderFile(context), stretchEffectShaderFile(context))
                .filter { it.isFile },
            licenseFiles = licenseFilesFromCache(context),
        )
        return buildFlutterAssets(flutterAssetsDir, projectRoot, sources, progress)
    }

    /**
     * **Nucleo puro (sin `android.*`)**: monta `flutter_assets/` a partir de las fuentes.
     *
     * Escribe, en este orden:
     * 1. `fonts/MaterialIcons-Regular.otf` (si viene en [Sources]).
     * 2. `shaders/<nombre>.frag` para cada shader de [Sources].
     * 3. `FontManifest.json` (familia `MaterialIcons` + familias declaradas en el pubspec).
     * 4. `AssetManifest.bin` (binario, `StandardMessageCodec`) + `AssetManifest.json` (espejo legible).
     * 5. `NOTICES.Z` (gzip).
     *
     * Solo `java.io`/`java.util.zip`: compilable y ejecutable en el host con `kotlinc` para validar
     * el formato sin Gradle (asi se verifico; ver `flutter-carril-A2.md`).
     */
    @JvmStatic
    @JvmOverloads
    fun buildFlutterAssets(
        flutterAssetsDir: File,
        projectRoot: File,
        sources: Sources,
        progress: (String) -> Unit = { },
    ): BundleAssetsResult {
        val log = StringBuilder()

        fun note(message: String) {
            log.append(message).append('\n')
            progress(message)
        }

        if (!flutterAssetsDir.mkdirs() && !flutterAssetsDir.isDirectory) {
            return BundleAssetsResult(false, false, 0, 0, 0, 0L,
                "No se pudo crear ${flutterAssetsDir.absolutePath}\n")
        }

        // --- 1) Fuente de iconos Material -------------------------------------------------------
        var fontIncluded = false
        val font = sources.materialIconsFont
        if (font != null && font.isFile) {
            val destination = File(File(flutterAssetsDir, FONTS_DIR), MATERIAL_ICONS_OTF)
            destination.parentFile?.mkdirs()
            font.copyTo(destination, overwrite = true)
            fontIncluded = destination.length() > 0
            note("[ok] ${MATERIAL_ICONS_ENTRY} (${destination.length()} B)")
        } else {
            note("[warn] sin $MATERIAL_ICONS_OTF: los iconos Material saldran como caja vacia")
        }

        // --- 2) Shaders ------------------------------------------------------------------------
        var shaderCount = 0
        val shadersDir = File(flutterAssetsDir, SHADERS_DIR)
        for (shader in sources.shaders) {
            if (!shader.isFile) {
                note("[warn] shader no encontrado: ${shader.absolutePath}")
                continue
            }
            shadersDir.mkdirs()
            shader.copyTo(File(shadersDir, shader.name), overwrite = true)
            shaderCount++
            note("[ok] $SHADERS_DIR/${shader.name} (${shader.length()} B)")
        }

        // --- 3) FontManifest.json --------------------------------------------------------------
        val fontManifest = buildFontManifestJson(projectRoot, fontIncluded)
        File(flutterAssetsDir, FONT_MANIFEST_FILE).writeText(fontManifest)
        note("[ok] $FONT_MANIFEST_FILE -> $fontManifest")

        // --- 4) AssetManifest.bin / .json ------------------------------------------------------
        val pubspec = File(projectRoot, "pubspec.yaml")
        val declared = parsePubspecAssets(pubspec)
        val entries = collectAssetEntries(projectRoot, declared)
        val variants = entries.values.sumOf { it.size } - entries.size
        File(flutterAssetsDir, ASSET_MANIFEST_BIN_FILE)
            .writeBytes(buildAssetManifestBinary(entries))
        File(flutterAssetsDir, ASSET_MANIFEST_JSON_FILE)
            .writeText(buildAssetManifestJson(entries))
        note("[ok] $ASSET_MANIFEST_BIN_FILE + $ASSET_MANIFEST_JSON_FILE " +
            "(${entries.size} entradas declaradas, $variants variantes)")

        // --- 5) NOTICES.Z ----------------------------------------------------------------------
        val noticesBytes = writeNoticesZ(
            File(flutterAssetsDir, NOTICES_Z_FILE),
            buildNoticesText(sources.licenseFiles),
        )
        note("[ok] $NOTICES_Z_FILE ($noticesBytes B gzip)")

        return BundleAssetsResult(
            success = fontIncluded && shaderCount > 0,
            fontIncluded = fontIncluded,
            shaderCount = shaderCount,
            assetEntryCount = entries.size,
            hiddenVariantCount = variants,
            noticesBytes = noticesBytes,
            log = log.toString(),
        )
    }

