    /**
     * Recorre lo declarado en `flutter: assets:` del pubspec y devuelve, por clave declarada, la
     * lista de ficheros reales (la clave misma + las variantes de densidad que existan al lado).
     *
     * Reglas replicadas de flutter_tools:
     * - una entrada que es **directorio** incluye todos los ficheros de dentro (recursivo);
     * - las carpetas con nombre `<N>x` (`2.0x`, `3x`, `1.5x`) son **variantes** de densidad y no
     *   se declaran como assets propios;
     * - los ficheros ocultos (`.` delante) se ignoran.
     */
    @JvmStatic
    fun collectAssetEntries(
        projectRoot: File,
        declared: List<String>,
    ): LinkedHashMap<String, List<String>> {
        val result = LinkedHashMap<String, List<String>>()
        for (declaration in declared) {
            val clean = normalizeAssetPath(declaration)
            if (clean.isEmpty()) continue
            val target = File(projectRoot, clean)
            val keys = when {
                target.isDirectory -> expandDirectory(projectRoot, target)
                target.isFile -> listOf(clean)
                else -> emptyList()
            }
            for (key in keys) {
                result[key] = variantsOf(projectRoot, key)
            }
        }
        return result
    }

    /** Ficheros reales de un directorio declarado (sin variantes de densidad ni ficheros ocultos). */
    private fun expandDirectory(projectRoot: File, directory: File): List<String> =
        directory.walkTopDown()
            .onEnter { child ->
                // Las carpetas de densidad se resuelven como variantes, no como assets propios.
                child == directory || !DENSITY_DIR_REGEX.matches(child.name)
            }
            .filter { it.isFile && !it.name.startsWith(".") }
            .map { it.relativeTo(projectRoot).invariantSeparatorsPath }
            .sorted()
            .toList()

    /** Clave + variantes de densidad contiguas (`assets/logo.png` -> `assets/2.0x/logo.png`). */
    private fun variantsOf(projectRoot: File, key: String): List<String> {
        val variants = ArrayList<String>()
        variants.add(key)
        val lastSlash = key.lastIndexOf('/')
        val directoryPart = if (lastSlash < 0) "" else key.substring(0, lastSlash)
        val fileName = key.substring(lastSlash + 1)
        val parent = if (directoryPart.isEmpty()) projectRoot else File(projectRoot, directoryPart)
        val siblings = parent.listFiles() ?: return variants
        for (sibling in siblings.sortedBy { it.name }) {
            if (!sibling.isDirectory || !DENSITY_DIR_REGEX.matches(sibling.name)) continue
            if (File(sibling, fileName).isFile) {
                variants.add(if (directoryPart.isEmpty()) sibling.name + "/" + fileName
                else directoryPart + "/" + sibling.name + "/" + fileName)
            }
        }
        return variants
    }

    /** `"./assets/x"`/`"/assets/x"`/`"assets\x"` -> `"assets/x"`. */
    @JvmStatic
    fun normalizeAssetPath(declaration: String): String {
        var value = declaration.trim().replace('\\', '/')
        while (value.startsWith("./")) value = value.substring(2)
        while (value.startsWith("/")) value = value.substring(1)
        while (value.endsWith("/")) value = value.dropLast(1)
        return value
    }

