    // pubspec.yaml (parser tolerante: solo `flutter: assets:` y `flutter: fonts:`)
    // ---------------------------------------------------------------------------------------------

    /** Familia de fuentes declarada en el pubspec. */
    class FontFamilySpec(@JvmField val family: String, @JvmField val fonts: List<FontAssetSpec>)

    /** Fuente concreta de una familia (`asset` + `weight`/`style` opcionales). */
    class FontAssetSpec(
        @JvmField val asset: String,
        @JvmField val weight: String? = null,
        @JvmField val style: String? = null,
    )

    /** Entradas `assets:` del bloque `flutter:` (tal cual, sin expandir directorios). */
    @JvmStatic
    fun parsePubspecAssets(pubspec: File): List<String> =
        listSection(pubspec, "assets:")

    /** Familias `fonts:` del bloque `flutter:`. */
    @JvmStatic
    fun parsePubspecFonts(pubspec: File): List<FontFamilySpec> {
        val block = flutterBlock(pubspec) ?: return emptyList()
        val keyIndex = indexOfKey(block, "fonts:")
        if (keyIndex < 0) return emptyList()
        val keyIndent = block[keyIndex].first
        val families = ArrayList<FontFamilySpec>()
        var currentFamily: String? = null
        var currentFonts = ArrayList<FontAssetSpec>()
        var pendingAsset: String? = null
        var pendingWeight: String? = null
        var pendingStyle: String? = null

        fun flushFont() {
            val asset = pendingAsset ?: return
            currentFonts.add(FontAssetSpec(asset, pendingWeight, pendingStyle))
            pendingAsset = null
            pendingWeight = null
            pendingStyle = null
        }

        fun flushFamily() {
            flushFont()
            val family = currentFamily ?: return
            families.add(FontFamilySpec(family, currentFonts))
            currentFamily = null
            currentFonts = ArrayList()
        }

        for (index in keyIndex + 1 until block.size) {
            val (indent, line) = block[index]
            if (line.isEmpty() || line.startsWith("#")) continue
            if (indent <= keyIndent && !line.startsWith("-")) break
            val item = line.removePrefix("-").trim()
            when {
                line.startsWith("-") && item.startsWith("family:") -> {
                    flushFamily()
                    currentFamily = unquote(item.substringAfter(':').trim())
                }
                item.startsWith("asset:") -> {
                    flushFont()
                    pendingAsset = unquote(item.substringAfter(':').trim())
                }
                item.startsWith("weight:") -> pendingWeight = item.substringAfter(':').trim()
                item.startsWith("style:") -> pendingStyle = item.substringAfter(':').trim()
            }
        }
        flushFamily()
        return families
    }

    /** Items (`- valor`) del bloque `flutter:` para la clave [key] (`"assets:"`). */
    private fun listSection(pubspec: File, key: String): List<String> {
        val block = flutterBlock(pubspec) ?: return emptyList()
        val keyIndex = indexOfKey(block, key)
        if (keyIndex < 0) return emptyList()
        val keyIndent = block[keyIndex].first
        val items = ArrayList<String>()
        for (index in keyIndex + 1 until block.size) {
            val (indent, line) = block[index]
            if (line.isEmpty() || line.startsWith("#")) continue
            if (line == key || line.startsWith(key)) continue
            if (indent <= keyIndent && !line.startsWith("-")) break
            val item = line.removePrefix("-").trim()
            if (line.startsWith("-") && item.isNotEmpty()) {
                items.add(unquote(item))
            } else if (item.isNotEmpty() && !item.contains(':')) {
                // Entradas sin guion (YAML acepta listas en linea de bloque) -> se acepta igual.
                items.add(unquote(item))
            }
        }
        return items
    }

    /** Lineas (indentacion, texto sin indentar) del bloque `flutter:` del pubspec. */
    private fun flutterBlock(pubspec: File): List<Pair<Int, String>>? {
        if (!pubspec.isFile) return null
        val lines = try {
            pubspec.readLines()
        } catch (e: Exception) {
            Log.w(TAG, "No se pudo leer ${pubspec.absolutePath}: ${e.message}")
            return null
        }
        val block = ArrayList<Pair<Int, String>>()
        var inside = false
        for (raw in lines) {
            val trimmed = raw.trim()
            val indent = raw.length - raw.trimStart().length
            if (!inside) {
                if (indent == 0 && trimmed == "flutter:") inside = true
                continue
            }
            if (trimmed.isEmpty()) continue
            if (indent == 0 && !trimmed.startsWith("#")) break
            block.add(indent to trimmed)
        }
        return if (inside) block else null
    }

    /** Indice de la clave [key] dentro del bloque (`-1` si no esta). */
    private fun indexOfKey(block: List<Pair<Int, String>>, key: String): Int =
        block.indexOfFirst { (_, line) -> line == key || line.startsWith("$key ") }

    /** Quita comillas simples/dobles de un valor YAML escalar. */
    private fun unquote(value: String): String {
        var result = value.trim()
        if (result.length >= 2 &&
            ((result.startsWith(""") && result.endsWith(""")) ||
                (result.startsWith("'") && result.endsWith("'")))
        ) {
            result = result.substring(1, result.length - 1)
        }
        return result
    }

    // ---------------------------------------------------------------------------------------------
    // NOTICES.Z
    // ---------------------------------------------------------------------------------------------

    /**
     * Texto de `NOTICES`: cada licencia como `"<paquetes>\n\n<texto>"`, unidas por el separador de
     * flutter_tools. Se incluye siempre el aviso del propio framework Flutter (BSD-3) porque el
     * paquete `flutter` es dependencia de todo proyecto; y por cada fichero de [licenseFiles] se
     * usa su nombre sin `_LICENSE.txt` como nombre de paquete.
     */
    @JvmStatic
    fun buildNoticesText(licenseFiles: List<File>): String {
        val entries = ArrayList<String>()
        entries.add("flutter\n\n$FLUTTER_LICENSE_TEXT")
        for (license in licenseFiles) {
            if (!license.isFile) continue
            val name = license.name.removeSuffix(LICENSE_SUFFIX)
            val text = try {
                license.readText(StandardCharsets.UTF_8)
            } catch (e: Exception) {
                Log.w(TAG, "No se pudo leer ${license.absolutePath}: ${e.message}")
                continue
            }
            entries.add("$name\n\n${text.trimEnd()}")
        }
        entries.sort()
        return entries.joinToString(LICENSE_SEPARATOR)
    }

    /**
     * Escribe `NOTICES.Z`: **gzip** del texto, que es lo que lee el framework
     * (`ServicesBinding._addLicenses` -> `gzip.decode`, ver `services/binding.dart`).
     *
     * NOTA HONESTA sobre el diccionario: flutter_tools comprime con un diccionario preajustado
     * (`hintString: 'copyrightsoftwaretothisinandorofthe'`) usando `package:archive`. El
     * decodificador del runtime es `const gzip = GZipCodec._default()`, que tiene
     * `dictionary = null`, y en **gzip** el diccionario preajustado no va en la cabecera: por eso
     * aqui se comprime **sin** diccionario (gzip estandar, nivel 9). Es la unica variante que el
     * motor puede descomprimir siempre; el contenido (el texto) es identico.
     */
    @JvmStatic
    fun writeNoticesZ(destination: File, noticesText: String): Long {
        destination.parentFile?.mkdirs()
        val compressed = gzip(noticesText.toByteArray(StandardCharsets.UTF_8))
        destination.writeBytes(compressed)
        return compressed.size.toLong()
    }

    /** gzip nivel 9 (mismo nivel que flutter_tools). */
    @JvmStatic
    fun gzip(data: ByteArray): ByteArray {
        val out = ByteArrayOutputStream(data.size / 2 + 64)
        LeveledGzipOutputStream(out, Deflater.BEST_COMPRESSION).use { gz ->
            gz.write(data)
            gz.finish()
        }
        return out.toByteArray()
    }

    /** `GZIPOutputStream` con nivel de compresion configurable (`def` es `protected`). */
    private class LeveledGzipOutputStream(out: OutputStream, level: Int) : GZIPOutputStream(out) {
        init {
            def.setLevel(level)
        }
    }

    // ---------------------------------------------------------------------------------------------
    // StandardMessageCodec (escritura) — el formato de AssetManifest.bin
    // ---------------------------------------------------------------------------------------------

    /**
     * Escribe [value] con las mismas etiquetas que `StandardMessageCodec` de Flutter
     * (`message_codecs.dart`): null=0, true=1, false=2, Int32=3, Int64=4, Float64=6, String=7,
     * Uint8List=8, List=12, Map=13. Los enteros van **big endian** (4/8 bytes) y los **tamanos**
     * (strings, listas, mapas) usan `writeSize`: 1 byte si `< 254`, si no `254`+uint16 o `255`+uint32.
     */
    @JvmStatic
    fun writeStandardValue(out: ByteArrayOutputStream, value: Any?) {
        when (value) {
            null -> out.write(0)
            is Boolean -> out.write(if (value) 1 else 2)
            is Int -> {
                out.write(3)
                writeInt32(out, value)
            }
            is Long -> {
                out.write(4)
                writeInt64(out, value)
            }
            is Double -> {
                out.write(6)
                writeInt64(out, java.lang.Double.doubleToLongBits(value))
            }
            is Float -> {
                out.write(6)
                writeInt64(out, java.lang.Double.doubleToLongBits(value.toDouble()))
            }
            is String -> {
                out.write(7)
                val bytes = value.toByteArray(StandardCharsets.UTF_8)
                writeSize(out, bytes.size)
                out.write(bytes, 0, bytes.size)
            }
            is ByteArray -> {
                out.write(8)
                writeSize(out, value.size)
                out.write(value, 0, value.size)
            }
            is List<*> -> {
                out.write(12)
                writeSize(out, value.size)
                for (item in value) writeStandardValue(out, item)
            }
            is Map<*, *> -> {
                out.write(13)
                writeSize(out, value.size)
                for ((key, entryValue) in value) {
                    writeStandardValue(out, key)
                    writeStandardValue(out, entryValue)
                }
            }
            else -> throw IllegalArgumentException(
                "StandardMessageCodec: tipo no soportado ${value.javaClass.name}"
            )
        }
    }

    /**
     * `writeSize` de `StandardMessageCodec`: los tamanos **no** son Int32 fijos.
     *
     * - `< 254` -> 1 byte;
     * - `<= 0xFFFF` -> byte `254` + uint16 big endian;
     * - resto -> byte `255` + uint32 big endian.
     *
     * (Este fue exactamente el bug que cazo el auto-test en el emulador: con un Int32 fijo, el
     * `decodeMessage` real lanzaba `FormatException: Message corrupted`. Reproducido y corregido
     * contra `services/message_codecs.dart`, `writeSize`/`readSize`.)
     */
    private fun writeSize(out: ByteArrayOutputStream, value: Int) {
        when {
            value < 254 -> out.write(value)
            value <= 0xFFFF -> {
                out.write(254)
                out.write((value ushr 8) and 0xFF)
                out.write(value and 0xFF)
            }
            else -> {
                out.write(255)
                writeInt32(out, value)
            }
        }
    }

    private fun writeInt32(out: ByteArrayOutputStream, value: Int) {
        out.write((value ushr 24) and 0xFF)
        out.write((value ushr 16) and 0xFF)
        out.write((value ushr 8) and 0xFF)
        out.write(value and 0xFF)
    }

    private fun writeInt64(out: ByteArrayOutputStream, value: Long) {
        out.write(((value ushr 56) and 0xFF).toInt())
        out.write(((value ushr 48) and 0xFF).toInt())
        out.write(((value ushr 40) and 0xFF).toInt())
        out.write(((value ushr 32) and 0xFF).toInt())
        out.write(((value ushr 24) and 0xFF).toInt())
        out.write(((value ushr 16) and 0xFF).toInt())
        out.write(((value ushr 8) and 0xFF).toInt())
        out.write((value and 0xFF).toInt())
    }

    // ---------------------------------------------------------------------------------------------
    // JSON minimo (sin depender de gson/xz: esto tiene que compilar y correr suelto)
    // ---------------------------------------------------------------------------------------------

    /** Serializa Map/List/String/Number/Boolean con el mismo formato compacto que `json.encode`. */
    @JvmStatic
    fun encodeJsonValue(value: Any?): String = when (value) {
        null -> "null"
        is String -> escapeJson(value)
        is Boolean -> value.toString()
        is Double -> if (value == value.toLong().toDouble()) "${value.toLong()}.0" else value.toString()
        is Number -> value.toString()
        is Map<*, *> -> value.entries.joinToString(separator = ",", prefix = "{", postfix = "}") {
            escapeJson(it.key.toString()) + ":" + encodeJsonValue(it.value)
        }
        is List<*> -> value.joinToString(separator = ",", prefix = "[", postfix = "]") {
            encodeJsonValue(it)
        }
        else -> escapeJson(value.toString())
    }

    private fun escapeJson(value: String): String {
        val builder = StringBuilder(value.length + 2)
        builder.append('"')
        for (c in value) {
            when (c) {
                '"' -> builder.append("\\\"")
                '\\' -> builder.append("\\\\")
                '\n' -> builder.append("\\n")
                '\r' -> builder.append("\\r")
                '\t' -> builder.append("\\t")
                else -> if (c < ' ') builder.append(String.format("\\u%04x", c.code))
                else builder.append(c)
            }
        }
        builder.append('"')
        return builder.toString()
    }

    // ---------------------------------------------------------------------------------------------
    // Base64 (propio: `java.util.Base64` exige API 26 y `android.util.Base64` romperia el nucleo puro)
    // ---------------------------------------------------------------------------------------------

    private const val B64_ALPHABET =
        "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"

    private val B64_LOOKUP = IntArray(128) { -1 }.also { table ->
        B64_ALPHABET.forEachIndexed { index, c -> table[c.code] = index }
    }

    private val DENSITY_DIR_REGEX = Regex("^(\\d+(\\.\\d*)?)x$")

    /** Base64 tolerante: ignora saltos de linea/espacios (los literales van troceados a 100). */
    @JvmStatic
    fun decodeBase64(text: String): ByteArray {
        val out = ByteArrayOutputStream(text.length * 3 / 4 + 4)
        var buffer = 0
        var bits = 0
        for (c in text) {
            if (c == '=') break
            if (c.code > 127) continue
            val value = B64_LOOKUP[c.code]
            if (value < 0) continue
            buffer = (buffer shl 6) or value
            bits += 6
            if (bits >= 8) {
                bits -= 8
                out.write((buffer shr bits) and 0xFF)
            }
        }
        return out.toByteArray()
    }
