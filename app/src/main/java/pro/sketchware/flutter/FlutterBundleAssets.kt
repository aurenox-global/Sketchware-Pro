    /** `<engine>/asset-sources`: cache local (nunca en la SD). */
    @JvmStatic
    fun assetSourcesDir(context: Context): File =
        File(FlutterToolchainPaths.engineDir(context), "asset-sources")

    /** `<engine>/asset-sources/material_fonts`: `fonts.zip` descomprimido. */
    @JvmStatic
    fun materialFontsDir(context: Context): File = File(assetSourcesDir(context), "material_fonts")

    /** `<engine>/asset-sources/shaders`: shaders ya precompilados (escritos desde base64). */
    @JvmStatic
    fun shadersSourceDir(context: Context): File = File(assetSourcesDir(context), SHADERS_DIR)

    @JvmStatic
    fun materialIconsFontFile(context: Context): File =
        File(materialFontsDir(context), MATERIAL_ICONS_OTF)

    @JvmStatic
    fun inkSparkleShaderFile(context: Context): File =
        File(shadersSourceDir(context), INK_SPARKLE_FRAG)

    @JvmStatic
    fun stretchEffectShaderFile(context: Context): File =
        File(shadersSourceDir(context), STRETCH_EFFECT_FRAG)

    /** `true` si estan la fuente Material y los dos shaders precompilados. */
    @JvmStatic
    fun areAssetSourcesReady(context: Context): Boolean =
        materialIconsFontFile(context).isFile &&
            inkSparkleShaderFile(context).isFile &&
            stretchEffectShaderFile(context).isFile

    /** Licencias textuales disponibles en la cache (para `NOTICES.Z`). */
    @JvmStatic
    fun licenseFilesFromCache(context: Context): List<File> {
        val dir = materialFontsDir(context)
        if (!dir.isDirectory) return emptyList()
        return (dir.listFiles() ?: emptyArray())
            .filter { it.isFile && it.name.endsWith(LICENSE_SUFFIX) }
            .sortedBy { it.name }
    }

    /**
     * Descarga/cachea las fuentes de assets. Bloqueante (llamar fuera del hilo de UI).
     *
     * - `fonts.zip` verificado por tamano **y** sha256 (reutiliza [FlutterToolchainInstaller.download]).
     * - Los shaders se **decodifican del base64 embebido** (ya vienen precompilados con `impellerc`).
     *
     * @return `true` si [areAssetSourcesReady] al terminar.
     */
    @JvmStatic
    fun ensureAssetSources(context: Context, progress: (String) -> Unit): Boolean {
        if (areAssetSourcesReady(context)) {
            progress("Assets de Flutter (fuente MaterialIcons + shaders) ya cacheados")
            return true
        }

        // 1) material_fonts (fonts.zip del SDK).
        val fontDir = materialFontsDir(context)
        if (!materialIconsFontFile(context).isFile) {
            val zip = File(FlutterToolchainPaths.downloadDir(context), "material_fonts.zip")
            progress("Descargando material_fonts (${MATERIAL_FONTS_SIZE / 1024} KB)...")
            if (!FlutterToolchainInstaller.download(
                    MATERIAL_FONTS_URL, zip, MATERIAL_FONTS_SIZE, MATERIAL_FONTS_SHA256, progress
                )
            ) {
                progress("No se pudo descargar $MATERIAL_FONTS_URL")
                return false
            }
            if (!fontDir.mkdirs() && !fontDir.isDirectory) {
                progress("No se pudo crear ${fontDir.absolutePath}")
                return false
            }
            // Se descomprime todo el zip (otf + licencias) con el unzip ya probado del carril C.
            if (!FlutterEngineArtifacts.unzip(zip, fontDir, progress)) {
                return false
            }
            val otf = materialIconsFontFile(context)
            if (!otf.isFile) {
                progress("fonts.zip no contiene $MATERIAL_ICONS_OTF")
                return false
            }
            if (otf.length() != MATERIAL_ICONS_OTF_SIZE) {
                // Solo aviso: el tamano del artefacto esta pinneado, pero un cambio de version
                // legitimo del SDK no debe romper el build (el sha256 del zip ya se verifico).
                progress("Aviso: $MATERIAL_ICONS_OTF = ${otf.length()} B (esperado $MATERIAL_ICONS_OTF_SIZE)")
            }
        }

        // 2) Shaders precompilados (base64 embebido -> fichero).
        val shaderDir = shadersSourceDir(context)
        if (!shaderDir.mkdirs() && !shaderDir.isDirectory) {
            progress("No se pudo crear ${shaderDir.absolutePath}")
            return false
        }
        writeShader(context, inkSparkleShaderFile(context), INK_SPARKLE_FRAG_BASE64,
            INK_SPARKLE_FRAG, INK_SPARKLE_FRAG_SIZE, progress)
        writeShader(context, stretchEffectShaderFile(context), STRETCH_EFFECT_FRAG_BASE64,
            STRETCH_EFFECT_FRAG, STRETCH_EFFECT_FRAG_SIZE, progress)

        val ready = areAssetSourcesReady(context)
        progress(if (ready) "Assets de Flutter listos (MaterialIcons + shaders)" else "Assets de Flutter incompletos")
        return ready
    }

    /** Escribe un shader desde el base64 embebido si falta o no cuadra el tamano. */
    private fun writeShader(
        context: Context,
        destination: File,
        base64: String,
        name: String,
        expectedSize: Long,
        progress: (String) -> Unit,
    ) {
        if (destination.isFile && destination.length() == expectedSize) {
            progress("Shader $name ya en cache")
            return
        }
        val bytes = decodeBase64(base64)
        if (bytes.size.toLong() != expectedSize) {
            progress("Shader $name: ${bytes.size} B (esperado $expectedSize)")
        }
        destination.parentFile?.mkdirs()
        destination.writeBytes(bytes)
        Log.d(TAG, "Shader $name escrito (${bytes.size} B) en ${destination.absolutePath}")
    }

